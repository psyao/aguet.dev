# Privacy policy

Last updated: 24 October 2026.

aguet.dev is the portfolio of Steve Aguet, a web developer in the Lake Geneva region of Switzerland. This site sells nothing, shows no ads and never sells any data. In line with the Swiss Federal Act on Data Protection (FADP), this page explains what data it processes and why.

## Data controller

Steve Aguet, Lake Geneva region, Switzerland. For any question about your data, write to me through the [contact form](/en#contact).

## Hosting

The site and its database are hosted in Switzerland by Infomaniak Network SA (Geneva). Like any web server, the host keeps technical logs (IP address, date, requested page, browser) to keep the service secure and running.

## Audience measurement

The site uses Cloudflare Web Analytics (Cloudflare, Inc., United States) to count visits in aggregate. It sets no cookie, uses no local storage and does not track visitors across sites.

## Cookies and local storage

The site sets only two technical cookies it needs to work: a session cookie and a cross-site request forgery (CSRF) protection token. Both expire after two hours of inactivity; meanwhile, the session also keeps your IP address and browser name in the site’s database. If you change the colour scheme, your choice is kept in your browser’s local storage and never leaves your device. Fonts are served by the site itself.

## Contact form

When you write to me, the site stores the subject, your email address and your message in its database at Infomaniak, then forwards them to me by email and through Infomaniak’s kChat messenger. This data is used only to reply to you; it is kept for as long as your request needs and deleted whenever you ask. Your IP address is used for about a minute to limit abusive submissions, and is not stored with your message.

## Your rights

You may ask to access, correct or delete your data, and object to its processing. If you visit from the European Union, the GDPR grants you the same rights. Write to me through the [contact form](/en#contact); I reply within 30 days.
