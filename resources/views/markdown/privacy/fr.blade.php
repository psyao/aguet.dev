# Politique de confidentialité

Dernière mise à jour : 24 octobre 2026.

aguet.dev est le portfolio de Steve Aguet, développeur web dans la région lémanique, en Suisse. Ce site ne vend rien, n’affiche aucune publicité et ne revend aucune donnée. Cette page explique, conformément à la loi fédérale sur la protection des données (nLPD), quelles données il traite et pourquoi.

## Responsable du traitement

Steve Aguet, région lémanique, Suisse. Pour toute question sur vos données, écrivez-moi via le [formulaire de contact](/#contact).

## Hébergement

Le site et sa base de données sont hébergés en Suisse par Infomaniak Network SA (Genève). Comme tout serveur web, l’hébergeur enregistre des journaux techniques (adresse IP, date, page demandée, navigateur) pour assurer la sécurité et le bon fonctionnement du service.

## Mesure d’audience

Le site utilise Cloudflare Web Analytics (Cloudflare, Inc., États-Unis) pour compter les visites de façon agrégée. Cet outil ne dépose aucun cookie, n’utilise pas le stockage local et ne suit pas les visiteurs d’un site à l’autre.

## Cookies et stockage local

Le site dépose uniquement deux cookies techniques, nécessaires à son fonctionnement : un cookie de session et un jeton de protection contre les requêtes falsifiées (CSRF). Ils expirent après deux heures d’inactivité ; pendant ce temps, la session garde aussi votre adresse IP et le nom de votre navigateur dans la base de données du site. Si vous changez le thème de couleurs, votre choix est gardé dans le stockage local de votre navigateur, qui ne quitte jamais votre appareil. Les polices sont hébergées sur le site lui-même.

## Formulaire de contact

Quand vous m’écrivez, le site enregistre l’objet, votre adresse e-mail et votre message dans sa base de données chez Infomaniak, puis me les transmet par e-mail et par la messagerie kChat d’Infomaniak. Ces données servent uniquement à vous répondre ; elles sont conservées le temps de traiter votre demande et supprimées sur simple demande. Votre adresse IP est utilisée environ une minute pour limiter les envois abusifs, sans être enregistrée avec votre message.

## Vos droits

Vous pouvez demander l’accès à vos données, leur rectification ou leur suppression, et vous opposer à leur traitement. Si vous visitez le site depuis l’Union européenne, le RGPD vous accorde les mêmes droits. Écrivez-moi via le [formulaire de contact](/#contact) ; je réponds dans les 30 jours.
